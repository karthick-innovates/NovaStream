class I18n {
  constructor() {
    this.currentLanguage = localStorage.getItem('novastream_lang');
  }

  setLanguage(lang) {
    if (!['en', 'ta'].includes(lang)) lang = 'en';
    this.currentLanguage = lang;
    localStorage.setItem('novastream_lang', lang);
    document.documentElement.lang = lang;
    
    // Update dropdown if exists
    const langSelect = document.getElementById('lang-select');
    if (langSelect) {
      langSelect.value = lang;
    }

    this.translateDOM();
  }

  translateDOM() {
    const elements = document.querySelectorAll('[data-i18n]');
    const dict = translations[this.currentLanguage] || translations['en'];
    
    elements.forEach(el => {
      const key = el.getAttribute('data-i18n');
      if (dict[key]) {
        // preserve icons if they exist inside the element
        let hasIcon = false;
        let iconHTML = '';
        const iconMatch = el.innerHTML.match(/(<i[^>]*>.*?<\/i>)/i);
        if (iconMatch) {
            hasIcon = true;
            iconHTML = iconMatch[1];
        }

        if (hasIcon) {
            el.innerHTML = iconHTML + ' ' + dict[key];
        } else {
            el.innerHTML = dict[key];
        }
      }
    });

    // Handle Placeholders
    const placeholders = document.querySelectorAll('[data-i18n-placeholder]');
    placeholders.forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      if (dict[key]) {
        el.setAttribute('placeholder', dict[key]);
      }
    });

    // Handle Titles
    const titles = document.querySelectorAll('[data-i18n-title]');
    titles.forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      if (dict[key]) {
        el.setAttribute('title', dict[key]);
      }
    });
  }

  t(key) {
    const dict = translations[this.currentLanguage] || translations['en'];
    return dict[key] || key;
  }
}

// Ensure global scope
window.i18n = new I18n();

// The setLanguage function called by index.html dropdown & modal
window.setLanguage = function(lang) {
    window.i18n.setLanguage(lang);
};
